export function getTranslation(key: string, lang: Language = 'ru'): string {
  const dict = TRANSLATIONS[lang] || TRANSLATIONS.ru;
  return dict[key] || TRANSLATIONS.en[key] || TRANSLATIONS.ru[key] || key;
}
